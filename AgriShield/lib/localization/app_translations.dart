  /// Translate [key] to [lang]. Falls back to English (the key itself) if not found.
  static String t(String key, String lang) {
    if (lang == 'en') return key;
    return _t[lang]?[key] ?? key;
  }

  /// Translate compound strings like "Potato - Early Blight" by splitting them if needed.
  static String translateCompound(String text, String lang) {
    if (lang == 'en') return text;
    
    // Fast path: try exact match first
    if (_t[lang]?.containsKey(text) ?? false) {
      return _t[lang]![text]!;
    }
    
    // Fallback: split by ' - ' and translate parts
    if (text.contains(' - ')) {
      final parts = text.split(' - ');
      final translatedParts = parts.map((p) => t(p, lang)).toList();
      return translatedParts.join(' - ');
    }
    
    return t(text, lang);
  }
